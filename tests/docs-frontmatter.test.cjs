'use strict'

// The frontmatter gate's YAML-scalar leg (rule #3: the bug was caught twice).
//
// The gate used to only regex-scan for `key: value`. That says nothing about
// whether YAML parses: an unquoted value carrying a colon-space is a YAML
// error, Jekyll then drops the WHOLE frontmatter block, and the page renders
// with no layout and no head injection. The bug shipped green in monoforge's
// docs/index.md, so the gate now validates every scalar and this leg proves
// it bites - including in a field the gate does not REQUIRE, because the
// monoforge bug landed in `description` and a variant gate that did not
// require it would have scanned past.

const test = require('node:test')
const assert = require('node:assert/strict')
const { spawnSync } = require('node:child_process')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const yaml = require('js-yaml')

const GATE = path.join(__dirname, '..', 'lib', 'gates', 'check-docs-frontmatter.cjs')

function fixture(frontmatter) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'coreforge-fm-'))
  fs.mkdirSync(path.join(root, 'docs'), { recursive: true })
  fs.writeFileSync(path.join(root, 'docs', 'index.md'), `---\n${frontmatter}\n---\n\n# page\n`)
  return root
}

function run(root) {
  const r = spawnSync('node', [GATE, '--root', root], { encoding: 'utf8' })
  return { code: r.status, out: `${r.stdout}\n${r.stderr}` }
}

const CLEAN = 'permalink: /\nlayout: default\ntitle: "Home"\ndescription: "a real description"'

test('a whole fixture page passes', () => {
  const r = run(fixture(CLEAN))
  assert.equal(r.code, 0, r.out)
  assert.match(r.out, /FRONTMATTER: PASS/)
})

test('an unquoted colon-space in a REQUIRED field is refused by name', () => {
  const r = run(fixture('permalink: /\nlayout: default\ntitle: "Home"\ndescription: slots: generated'))
  assert.equal(r.code, 1, r.out)
  assert.match(r.out, /description.*colon-space/)
})

test('an unquoted colon-space in a NON-required field is refused too (the monoforge shape)', () => {
  const r = run(fixture(`${CLEAN}\nauthor: slots: generated by the factory`))
  assert.equal(r.code, 1, r.out)
  assert.match(r.out, /author.*colon-space/)
})

test('a quoted value with a colon-space is fine', () => {
  const r = run(fixture('permalink: /\nlayout: default\ntitle: "Home"\ndescription: "slots: generated"'))
  assert.equal(r.code, 0, r.out)
})

// --- The nav/permalink route law ------------------------------------------
//
// Jekyll resolves `permalink: cli` to `cli.html`, but `permalink: cli/` to
// `cli/index.html`. freestruct's link checker reads a trailing-slash href as a
// DIRECTORY route (engine/linkcheck.js: dirIndex first, then the .html
// sibling), so a nav link `/cli/` against a page built as `cli.html` is a real
// 404 that the strict gate catches - and a nav link that does NOT match the
// page's own route is the class of bug that hid under the old
// `linkCheck: false` workaround. Verified against a real Jekyll build: the
// mismatch produced `cli.html` and the checker reported `/coreforge/cli/`
// broken; `permalink: cli/` produces `cli/index.html` and the check is clean.
//
// The law: every nav.yml url that names a docs page must resolve to that
// page's route. A trailing-slash url requires a directory-shaped permalink;
// a bare url requires the flat .html shape. This guards the shipped nav +
// pages (no Jekyll needed - the permalink IS the route the build will emit).

const REPO = path.join(__dirname, '..')

function navUrls() {
  const nav = yaml.load(fs.readFileSync(path.join(REPO, 'docs', '_data', 'nav.yml'), 'utf8'))
  const urls = []
  for (const group of nav) for (const item of group.items || []) urls.push(item.url)
  return urls
}

function permalinks() {
  // slug -> permalink, for every top-level docs page (index.md lives at '/').
  const map = new Map()
  const docs = path.join(REPO, 'docs')
  for (const e of fs.readdirSync(docs, { withFileTypes: true })) {
    if (e.isDirectory()) {
      const idx = path.join(docs, e.name, 'index.md')
      if (fs.existsSync(idx)) map.set(e.name, frontmatterPermalink(idx))
      continue
    }
    if (e.name.endsWith('.md') && e.name !== 'index.md') map.set(e.name.replace(/\.md$/, ''), frontmatterPermalink(path.join(docs, e.name)))
  }
  return map
}

function frontmatterPermalink(file) {
  const m = fs.readFileSync(file, 'utf8').match(/^---\n([\s\S]*?)\n---/)
  const p = (m ? m[1] : '').match(/^permalink:\s*(.+)$/m)
  return p ? p[1].trim() : ''
}

test('every nav url resolves to a real docs route (the trailing-slash law)', () => {
  // The law is one-directional, matching the checker (engine/linkcheck.js): a
  // FLAT href (`/cli`) resolves against a directory index OR the .html
  // sibling, so it is fine either way. A TRAILING-SLASH href (`/cli/`) is
  // read as a directory route ONLY - index first, then the .html sibling -
  // so it requires a directory-shaped permalink. A trailing nav link against
  // a flat page is the real 404 (the bug this guards); the reverse is valid.
  const perms = permalinks()
  const offenders = []
  for (const url of navUrls()) {
    if (url === '/') continue // index.md
    if (!url.endsWith('/')) continue // a flat href resolves either shape
    const slug = url.replace(/^\/+/, '').replace(/\/+$/, '')
    const perm = perms.get(slug)
    if (perm === undefined) { offenders.push(`${url} -> no docs page named "${slug}"`); continue }
    if (!perm.endsWith('/')) {
      offenders.push(`${url} -> docs/${slug}.md has flat permalink "${perm}" (builds ${slug}.html); a trailing nav link needs a directory route (permalink: ${slug}/)`)
    }
  }
  assert.deepEqual(offenders, [], `nav.yml trailing-slash links must resolve to a directory route:\n${offenders.join('\n')}`)
})

test('the nav/permalink law bites: a trailing nav link against a flat permalink fails', () => {
  // The exact pre-fix shape: nav `/cli/` (directory) vs `permalink: cli`
  // (flat, builds cli.html). The guard must refuse it - and must NOT flag the
  // valid reverse (flat nav link against a directory page), which eyestruct
  // ships throughout.
  const ok = (url, perm) => !url.endsWith('/') || perm.endsWith('/')
  assert.equal(ok('/cli/', 'cli'), false, 'trailing nav link against a flat permalink must be refused')
  assert.equal(ok('/cli/', 'cli/'), true, 'trailing nav link against a directory permalink is fine')
  assert.equal(ok('/cli', 'cli/'), true, 'a flat nav link against a directory page is valid (eyestruct pattern)')
  assert.equal(ok('/cli', 'cli'), true, 'a flat nav link against a flat page is valid')
})
