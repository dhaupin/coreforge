#!/usr/bin/env node
// bin/coreforge.mjs - the coreforge CLI: create / sync / build / check / doctor
// (PRD 6). Zero-dependency. The load-bearing law is monoforge's: generated
// green is never shipped - the doctor refuses placeholder residue, a stale
// derived surface, and a failing gate. An unfilled slot is a failure, not a
// warning.
//
// The verbs:
//   create [dir]   scaffold the shell into <dir> from site.config.js answers
//                  (or a site.json in the target). Never clobbers existing files.
//   sync           regenerate the derived surfaces from site.config.js.
//   build          validate config, vite build, repair + verify 404.
//   check          the gates over the adopter's tree (this is the verb CI calls).
//   doctor [dir]   the truth battery: config, placeholder residue, derived
//                  freshness, then check. Exit 0 only when nothing failed.
//
// The tool half (lib/) travels to an adopter by `npm install coreforge`; the
// site half travels by `create` (templates/site + templates/adopter). The
// gates resolve the SITE root by walking up to site.config.js, so one code
// path serves both the dogfood and an installed adopter.
import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync, copyFileSync } from 'node:fs'
import { join, dirname, relative, resolve } from 'node:path'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const SELF = dirname(fileURLToPath(import.meta.url))
const PKG_ROOT = resolve(SELF, '..')
const TEMPLATE = join(PKG_ROOT, 'templates', 'site')
const ADOPTER = join(PKG_ROOT, 'templates', 'adopter')
const pkg = JSON.parse(readFileSync(join(PKG_ROOT, 'package.json'), 'utf8'))

const Help = `coreforge - the struct-family site shell

Usage:
  coreforge create [dir]     scaffold the shell into <dir> (default: cwd)
                             from a site.json answer file or flags. Never
                             clobbers existing files.
  coreforge sync [dir]       regenerate the derived surfaces from site.config.js
                             (--check refuses drift instead of writing)
  coreforge build [dir]      validate config, vite build, repair + verify 404
  coreforge check [dir]      the gates over the tree (this is the verb CI calls)
  coreforge doctor [dir]     the truth battery: config, placeholder residue,
                             derived freshness, then check. Exit 0 is PASS only
                             when nothing failed.
  coreforge verify-release   the post-publish trust ladder (--npm / --gh --tag)
  coreforge release-notes    extract the CHANGELOG section for a version
  coreforge lint-packs [dir] packstruct lint over the tree's own install
  coreforge --version        print the installed version
  coreforge help             this

The site identity lives once in site.config.js; every other surface derives
from it (JS imports it, the non-JS surfaces are generated by sync). The brand
census gate refuses an identity literal that lives anywhere else.

create answers (flags or <dir>/site.json):
  { "name": "acme", "url": "https://acme.creadev.org",
    "repo": "https://github.com/acme/acme",
    "docsHost": "docs.creadev.org", "docsBaseurl": "/acme",
    "org": "https://github.com/acme", "author": "acme",
    "makerLabel": "acme", "orgName": "acme",
    "wordmarkAccent": "ac", "wordmarkRest": "me" }
`

const [cmd, ...rest] = process.argv.slice(2)
const positional = rest.filter((a) => !a.startsWith('--'))
const dir = resolve(positional[0] || '.')
const gate = (rel) => join(PKG_ROOT, 'lib', rel)
// A passthrough verb forwards the raw args to a lib script, run from <cwd>
// (the adopter's root) so the script's own cwd-relative resolution is right.
const passthrough = (rel, args, cwd) =>
  spawnSync(process.execPath, [gate(rel), ...args], { stdio: 'inherit', cwd }).status ?? 1

if (!cmd || cmd === 'help' || cmd === '--help') { console.log(Help); process.exit(0) }
if (cmd === '--version') { console.log(pkg.version); process.exit(0) }

// --- check: the gates over a tree -----------------------------------------
// Each gate is a child run with --root <dir>; we keep going and report the
// tally so one run names every failure (CI reads the exit code).
function checkTree(root) {
  const legs = [
    ['gates/check-docs-frontmatter.cjs', 'docs frontmatter'],
    ['gates/check-docs-links.cjs', 'docs links'],
    ['gates/check-docs-style.cjs', 'docs style'],
    ['gates/check-fiction-signatures.cjs', 'fiction signatures'],
    ['gates/check-jekyll-filters.cjs', 'Liquid filters'],
    ['gates/check-theme-parity.cjs', 'theme parity'],
    ['gates/check-language.cjs', 'language'],
    ['gates/check-birth-gate.cjs', 'birth-gate'],
    ['gates/check-brand-census.mjs', 'brand census'],
  ]
  let failed = 0
  for (const [rel, name] of legs) {
    const r = spawnSync(process.execPath, [gate(rel), '--root', root], { stdio: 'inherit' })
    if (r.status !== 0) { console.error(`coreforge check: ${name} FAILED`); failed++ }
  }
  return failed
}

// --- sync ------------------------------------------------------------------
function syncTree(root, check) {
  const args = [gate('sync.mjs'), '--root', root]
  if (check) args.push('--check')
  return spawnSync(process.execPath, args, { stdio: 'inherit' }).status ?? 1
}

// --- build -----------------------------------------------------------------
function buildTree(root) {
  if (!existsSync(join(root, 'web', 'package.json'))) {
    console.error(`coreforge build: ${root}/web has no package.json - is this a stamped site?`)
    return 1
  }
  if (!existsSync(join(root, 'web', 'node_modules'))) {
    const inst = spawnSync('npm', ['install', '--no-audit', '--no-fund'], { cwd: join(root, 'web'), stdio: 'inherit' })
    if (inst.status !== 0) return 1
  }
  return spawnSync('npm', ['run', 'build'], { cwd: join(root, 'web'), stdio: 'inherit' }).status ?? 1
}

// --- create ----------------------------------------------------------------
function readAnswers(root) {
  const flags = {}
  for (let i = 0; i < rest.length; i++) {
    const a = rest[i]
    if (a === '--name') flags.name = rest[++i]
    else if (a === '--url') flags.url = rest[++i]
    else if (a === '--repo') flags.repo = rest[++i]
    else if (a === '--org') flags.org = rest[++i]
    else if (a === '--author') flags.author = rest[++i]
  }
  const answersFile = join(root, 'site.json')
  if (existsSync(answersFile)) return { ...JSON.parse(readFileSync(answersFile, 'utf8')), ...flags }
  return flags
}

function walkTemplate(rootDir, rel, acc) {
  for (const e of readdirSync(rootDir, { withFileTypes: true })) {
    const r = rel ? `${rel}/${e.name}` : e.name
    if (e.isDirectory()) walkTemplate(join(rootDir, e.name), r, acc)
    else acc.push(r)
  }
}

function create(root) {
  if (!existsSync(TEMPLATE)) {
    console.error(`coreforge create: the site template is missing (${TEMPLATE}) - a broken install`)
    return 1
  }
  const answers = readAnswers(root)
  const missing = ['name', 'url', 'repo'].filter((k) => !answers[k])
  if (missing.length) {
    console.error(`coreforge create: missing ${missing.join(', ')} - pass --name/--url/--repo (or a site.json in the target)`)
    console.error('  (the interactive prompt lands in a later pass; the answers file is the scriptable contract today)')
    return 1
  }
  const host = answers.docsHost || 'docs.creadev.org'
  const baseurl = answers.docsBaseurl || `/${answers.name}`
  const site = {
    name: answers.name,
    url: answers.url,
    repo: answers.repo,
    org: answers.org || `https://github.com/${(String(answers.repo).split('/')[3] || answers.name)}`,
    author: answers.author || answers.name,
    docsHost: host,
    docsBaseurl: baseurl,
    docsUrl: answers.docsUrl || `${host}${baseurl}`,
    makerLabel: answers.makerLabel || answers.name,
    orgName: answers.orgName || answers.name,
    wordmarkAccent: answers.wordmarkAccent || answers.name.slice(0, 4),
    wordmarkRest: answers.wordmarkRest || answers.name.slice(4),
  }

  const TOKENS = [
    ['__DOCS_URL__', site.docsUrl],
    ['__SITE_URL__', site.url],
    ['__REPO_URL__', site.repo],
    ['__DOCS_HOST__', site.docsHost],
    ['__ORG_URL__', site.org],
    ['__MAKER_LABEL__', site.makerLabel],
    ['__ORG_NAME__', site.orgName],
    ['__DOCS_BASEURL__', site.docsBaseurl],
    ['__WORDMARK__', `{ accent: '${site.wordmarkAccent}', rest: '${site.wordmarkRest}' }`],
    ['__NAME__', site.name],
    ['__AUTHOR__', site.author],
    ['__LANE_REPO__', 'dhaupin/freestruct'],
    ['__COREFORGE_VERSION__', pkg.version],
  ]
  const fill = (text) => {
    let out = text
    for (const [tok, val] of TOKENS) out = out.split(tok).join(val)
    return out
  }

  // The adopter's own CI lanes: the site template excludes them (they are
  // coupled to the coreforge package), so `create` stamps the adopter-safe
  // pair wired to the installed tool.
  const rels = []
  walkTemplate(TEMPLATE, '', rels)
  walkTemplate(ADOPTER, '', rels)
  const created = []
  const skipped = []
  for (const rel of rels) {
    const src = existsSync(join(TEMPLATE, rel)) ? join(TEMPLATE, rel) : join(ADOPTER, rel)
    const dest = join(root, rel)
    if (existsSync(dest)) { skipped.push(rel); continue }
    mkdirSync(dirname(dest), { recursive: true })
    if (/\.(png|jpe?g|ico|woff2?|ttf|otf|gif|webp|avif|pdf)$/i.test(rel)) copyFileSync(src, dest)
    else writeFileSync(dest, fill(readFileSync(src, 'utf8')))
    created.push(rel)
  }

  // Placeholder residue: a token that survived the fill (the answer set missed
  // a form) would ship a broken site. Refuse at cause, named.
  const residue = []
  for (const rel of created) {
    if (/\.(png|jpe?g|ico|woff2?|ttf|otf|gif|webp|avif|pdf)$/i.test(rel)) continue
    const m = readFileSync(join(root, rel), 'utf8').match(/__[A-Z][A-Z_]*__/)
    if (m) residue.push(`${rel}: unfilled placeholder ${m[0]}`)
  }
  console.log(`create: wrote ${created.length} file(s) into ${root}/`)
  if (skipped.length) console.log(`create: skipped ${skipped.length} existing file(s) (never clobber): ${skipped.slice(0, 6).join(', ')}${skipped.length > 6 ? ', ...' : ''}`)
  if (residue.length) {
    console.error('create: FAIL (placeholder residue - the answer set is incomplete)')
    for (const r of residue) console.error('  ' + r)
    return 1
  }
  console.log('create: next - npm install, then `coreforge doctor`')
  return 0
}

// --- doctor ----------------------------------------------------------------
function doctor(root) {
  const findings = []
  if (!existsSync(join(root, 'site.config.js'))) {
    findings.push('no site.config.js - not a stamped site (run `coreforge create`)')
  }
  // Placeholder residue anywhere in the shipped tree (the FORGE-TODO law).
  const residueRe = /__[A-Z][A-Z_]*__|FORGE-TODO|YOUR-NAME|YOURNAME/
  const scan = (d) => {
    for (const e of readdirSync(d, { withFileTypes: true })) {
      if (e.name === 'node_modules' || e.name === '.git' || e.name === 'dist' || e.name === '_site') continue
      const p = join(d, e.name)
      if (e.isDirectory()) { scan(p); continue }
      if (/\.(png|jpe?g|ico|woff2?|ttf|otf|gif|webp|avif|pdf|lock)$/i.test(e.name)) continue
      const m = readFileSync(p, 'utf8').match(residueRe)
      if (m) findings.push(`${relative(root, p)}: placeholder residue "${m[0]}" - generated green is never shipped`)
    }
  }
  if (existsSync(root)) scan(root)
  const sc = spawnSync(process.execPath, [gate('sync.mjs'), '--root', root, '--check'], { encoding: 'utf8' })
  if (sc.status !== 0) findings.push('derived surfaces are stale - run `coreforge sync`')
  const failed = checkTree(root)
  if (failed) findings.push(`${failed} gate(s) failed`)

  for (const msg of findings) console.log(`FAIL ${msg}`)
  console.log(`doctor: ${findings.length} fail(s) - ${findings.length ? 'FAIL' : 'PASS'}`)
  return findings.length ? 1 : 0
}

// --- dispatch --------------------------------------------------------------
let code = 0
if (cmd === 'check') code = checkTree(dir) ? 1 : 0
else if (cmd === 'sync') code = syncTree(dir, rest.includes('--check'))
else if (cmd === 'build') code = buildTree(dir)
else if (cmd === 'create') code = create(dir)
else if (cmd === 'doctor') code = doctor(dir)
else if (cmd === 'verify-release') code = passthrough('verify-release.cjs', rest, process.cwd())
else if (cmd === 'release-notes') code = passthrough('release-notes.cjs', rest, process.cwd())
else if (cmd === 'lint-packs') code = passthrough('lint-packs.cjs', rest, process.cwd())
else { console.error(`coreforge: unknown verb "${cmd}"\n`); console.log(Help); code = 2 }
process.exit(code)
